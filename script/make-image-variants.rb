#!/usr/bin/env ruby
# frozen_string_literal: true

# Generates, ONCE, the committed responsive variants of the site's pictures (no image tooling
# runs in CI):
#
#   assets/img/{projects,blog,motioforge}/<name>.webp   ->  <name>-480.webp, <name>-800.webp, <name>-1200.webp
#   assets/team/<name>.webp                             ->  <name>-260.webp, <name>-520.webp
#   _data/image_variants.yml                            the manifest: for each master its pixel
#                                                       size and the variant widths that exist
#
# The master stays the largest candidate of the srcset (width = its own pixel width), so a
# 1200px picture has variants 480 and 800 and the master itself as its 1200w. A variant is made
# only when it is at most 90% of the master's width (no point in a 1080px copy of a 1200px
# picture) and smaller in bytes than the master; a picture that gets no variant (a 260px
# portrait, a 300px cover) is listed with an empty `variants` and is served as it is.
#
# _includes/picture.html reads the manifest (size + variants) to write src, srcset, width,
# height and sizes; script/checks/perf.rb proves that every variant listed exists, is a real
# WebP of the stated width, and that no <img> wider than 480px lacks a srcset.
#
# Run it again, and commit the files, when a picture is added or replaced:
#
#   ruby script/make-image-variants.rb          # only what is missing or older than its master
#   ruby script/make-image-variants.rb --force  # everything again
#
# Needs: cwebp (libwebp) and identify (ImageMagick). Lossy variants at quality 78, method 6.

require "fileutils"
require "open3"
require "yaml"

ROOT = File.expand_path("..", __dir__)
Dir.chdir(ROOT)

# [glob of the masters, variant widths]
GROUPS = [
  ["assets/img/{projects,blog,motioforge}/*.webp", [480, 800, 1200]],
  ["assets/team/*.webp", [260, 520]]
].freeze
MANIFEST = "_data/image_variants.yml"
QUALITY = "78"
MAX_SHARE = 0.9
VARIANT_NAME = /-(?:260|480|520|800|1200)\.webp\z/

def run(*cmd)
  out, err, status = Open3.capture3(*cmd)
  abort "#{cmd.join(" ")} failed: #{err}" unless status.success?
  out
end

def size_of(path)
  w, h = run("identify", "-format", "%w %h", "#{path}[0]").split.map(&:to_i)
  [w, h]
end

force = ARGV.include?("--force")
manifest = {}
made = 0
kept = 0
expected = []

GROUPS.each do |glob, widths|
  Dir.glob(glob).sort.reject { |path| path.match?(VARIANT_NAME) }.each do |master|
    w, h = size_of(master)
    base = master.sub(/\.webp\z/, "")
    kept_widths = []
    widths.each do |v|
      next unless v <= w * MAX_SHARE

      out = "#{base}-#{v}.webp"
      expected << out
      if force || !File.file?(out) || File.mtime(out) < File.mtime(master)
        run("cwebp", "-quiet", "-q", QUALITY, "-m", "6", "-mt", "-resize", v.to_s, "0", master, "-o", out)
        made += 1
      else
        kept += 1
      end
      if File.size(out) >= File.size(master)
        puts "skip #{out}: not smaller than its master (#{File.size(out)} >= #{File.size(master)} bytes)"
        FileUtils.rm_f(out)
        expected.delete(out)
        next
      end
      kept_widths << v
    end
    manifest["/#{master}"] = { "width" => w, "height" => h, "variants" => kept_widths }
  end
end

# A variant whose master is gone, or that is no longer wanted, must not stay in the repository.
GROUPS.each do |glob, _|
  Dir.glob(glob).select { |path| path.match?(VARIANT_NAME) && !expected.include?(path) }.each do |stale|
    FileUtils.rm_f(stale)
    puts "removed stale #{stale}"
  end
end

header = <<~TEXT
  # Generated by script/make-image-variants.rb. Do not edit.
  # For each picture: its pixel size and the variant widths that exist next to it as
  # <name>-<width>.webp. _includes/picture.html builds src, srcset and the size attributes from it.
TEXT
body = manifest.sort.map do |src, info|
  "#{src}:\n  width: #{info["width"]}\n  height: #{info["height"]}\n  variants: [#{info["variants"].join(", ")}]\n"
end.join
File.write(MANIFEST, header + body)

total_master = manifest.keys.sum { |k| File.size(k.delete_prefix("/")) }
puts "#{manifest.size} pictures, #{made} variant(s) written, #{kept} up to date (master bytes: #{total_master})"
