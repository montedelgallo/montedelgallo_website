#!/usr/bin/env ruby
# frozen_string_literal: true

# Generates the nginx form of the redirect map (_data/redirects.yml) into
# deploy/nginx/redirects.conf. The Cloudflare Pages / Netlify form (_site/_redirects) is
# built by Jekyll from redirects.txt; this file holds the same rules in Ruby
# (BuildRedirects.cloudflare) so script/checks/redirects_emit.rb can prove the two agree.
#
#   bundle exec ruby script/build-redirects.rb          # rewrite deploy/nginx/redirects.conf
#   bundle exec ruby script/build-redirects.rb --check  # exit 1 when the committed file is stale
#
# Rules (one source of truth, _data/redirects.yml, in file order):
#   * every entry is a 301 from `from` (a /path/) to `to` (a path, optionally #anchor);
#   * every `from` is also served without its trailing slash (/path): the old WordPress
#     answered both, and a static host does not redirect a URL that has no file;
#   * nothing else: no wildcard, no query rule (see the notes in _data/redirects.yml).

require "yaml"

module BuildRedirects
  DATA = File.expand_path("../_data/redirects.yml", __dir__)
  NGINX_FILE = File.expand_path("../deploy/nginx/redirects.conf", __dir__)

  module_function

  # [[from, to], ...] in file order, one pair per source URL: the slash form first, then the
  # form without the slash.
  def rules
    YAML.safe_load(File.read(DATA, encoding: "utf-8")).flat_map do |entry|
      from = entry.fetch("from")
      [[from, entry.fetch("to")], [from.chomp("/"), entry.fetch("to")]]
    end
  end

  # The body of _site/_redirects (Cloudflare Pages, Netlify): `from to 301` per line.
  def cloudflare
    rules.map { |from, to| "#{from} #{to} 301\n" }.join
  end

  # deploy/nginx/redirects.conf: include it inside the server block.
  def nginx
    header = <<~CONF
      # Generated by script/build-redirects.rb from _data/redirects.yml. Do not edit by hand:
      # change the data and run `bundle exec ruby script/build-redirects.rb`.
      # Include inside the server block of montedelgallo.com. The target is quoted because an
      # unquoted # starts a comment in nginx, and the #anchor of a target must reach the client.
    CONF
    header + rules.map { |from, to| "location = #{from} { return 301 \"#{to}\"; }\n" }.join
  end
end

if $PROGRAM_NAME == __FILE__
  if ARGV.include?("--check")
    current = File.exist?(BuildRedirects::NGINX_FILE) ? File.read(BuildRedirects::NGINX_FILE, encoding: "utf-8") : nil
    if current == BuildRedirects.nginx
      puts "deploy/nginx/redirects.conf is up to date"
    else
      warn "deploy/nginx/redirects.conf is stale: run script/build-redirects.rb"
      exit 1
    end
  else
    File.write(BuildRedirects::NGINX_FILE, BuildRedirects.nginx, encoding: "utf-8")
    puts "wrote deploy/nginx/redirects.conf (#{BuildRedirects.rules.size} rules)"
  end
end
